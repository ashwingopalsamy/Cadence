#!/usr/bin/env python3
"""Embeds integrations/claude-code/hooks.json and skills/cadence/SKILL.md in the cadence binary.

`cadence setup claude-code` has to work from ~/.local/bin with no repo around, so the two files are copied into
Sources/CadenceCore/Integration/EmbeddedClaudeCodeFiles.swift as raw string constants. The Swift test
EmbeddedIntegrationTests keeps the copy equal to the files byte for byte.

Usage:
  tools/embed_claude_code.py          rewrite the Swift file
  tools/embed_claude_code.py --check  exit 1 when the Swift file is out of date
"""
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
SOURCES = {
    "hooksJSON": ROOT / "integrations/claude-code/hooks.json",
    "skillMarkdown": ROOT / "integrations/claude-code/skills/cadence/SKILL.md",
}
TARGET = ROOT / "Sources/CadenceCore/Integration/EmbeddedClaudeCodeFiles.swift"

HEADER = """// Generated by tools/embed_claude_code.py from integrations/claude-code. Do not edit by hand.
// EmbeddedIntegrationTests fails when this file and the integration files differ.

enum EmbeddedClaudeCodeFiles {
"""


def literal(name: str, path: pathlib.Path) -> str:
    text = path.read_bytes().decode("utf-8")
    if "\r" in text:
        sys.exit(f"{path}: carriage returns cannot be embedded; use LF line endings")
    if '"""#' in text:
        sys.exit(f"{path}: contains the string delimiter")
    if not text.endswith("\n"):
        sys.exit(f"{path}: must end with a newline")
    # The closing delimiter sits at column 0, so nothing is stripped. The text before it ends with the
    # file's last newline, which the empty line below restores.
    return f'    static let {name} = #"""\n{text}\n"""#\n'


def render() -> str:
    return HEADER + "\n".join(literal(name, path) for name, path in SOURCES.items()) + "}\n"


def main() -> int:
    wanted = render()
    if "--check" in sys.argv[1:]:
        if not TARGET.exists() or TARGET.read_text(encoding="utf-8") != wanted:
            print(f"{TARGET.relative_to(ROOT)} is out of date; run tools/embed_claude_code.py", file=sys.stderr)
            return 1
        return 0
    TARGET.write_text(wanted, encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main())
